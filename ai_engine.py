def has_trigger_keywords(text: str) -> bool:
    if not text or len(text.strip()) < 15:
        return False
    text_clean = text.strip()
    if EXCLUDE_REGEX.search(text_clean):
        return False
    return bool(TRIGGER_REGEX.search(text_clean))

