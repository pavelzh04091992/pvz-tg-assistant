async def evaluate_and_generate_reply(message_text: str, author_name: str) -> dict:
    if not OPENROUTER_API_KEY:
        logger.error("OPENROUTER_API_KEY is not set!")
        return {"should_reply": False, "reason": "No API key"}

    url = "https://openrouter.ai/api/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {OPENROUTER_API_KEY}",
        "HTTP-Referer": "https://github.com/pvz-finance",
        "X-Title": "PVZ Guerrilla Assistant",
        "Content-Type": "application/json"
    }

    user_content = f"Участник '{author_name}' написал в чате:\n\"{message_text}\""

    payload = {
        "model": OPENROUTER_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_content}
        ],
        "response_format": {"type": "json_object"},
        "max_tokens": 1000,
        "temperature": 0.7
    }

    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(url, headers=headers, json=payload)
            if resp.status_code != 200:
                logger.error(f"OpenRouter error {resp.status_code}: {resp.text}")
                return {"should_reply": False, "reason": f"API error {resp.status_code}"}

            res_json = resp.json()
            content = res_json['choices'][0]['message']['content']
            
            if content.startswith("```"):
                content = re.sub(r"^```(?:json)?\n|\n```$", "", content.strip())
            
            data = json.loads(content)
            return data
    except Exception as e:
        logger.error(f"Error calling OpenRouter: {e}")
        return {"should_reply": False, "reason": str(e)}
